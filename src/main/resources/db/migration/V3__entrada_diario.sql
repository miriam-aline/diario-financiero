CREATE TABLE entrada_diario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    nota VARCHAR(4000) NOT NULL,
    estado_de_animo INT,
    etiquetas VARCHAR(500),
    CONSTRAINT uk_entrada_diario_fecha UNIQUE (fecha),
    CONSTRAINT ck_entrada_diario_animo CHECK (estado_de_animo IS NULL OR (estado_de_animo BETWEEN 1 AND 5))
);

CREATE INDEX idx_entrada_diario_fecha ON entrada_diario (fecha);
