CREATE TABLE recurrente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL,
    monto DECIMAL(19, 2) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    categoria_id BIGINT NOT NULL,
    cuenta_id BIGINT NOT NULL,
    periodicidad VARCHAR(20) NOT NULL,
    dia_referencia INT NOT NULL,
    proximo_cobro DATE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_recurrente_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_recurrente_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT ck_recurrente_monto_positivo CHECK (monto > 0),
    CONSTRAINT ck_recurrente_tipo CHECK (tipo IN ('INGRESO', 'GASTO')),
    CONSTRAINT ck_recurrente_periodicidad CHECK (periodicidad IN ('QUINCENAL', 'MENSUAL', 'ANUAL')),
    CONSTRAINT ck_recurrente_dia_ref CHECK (dia_referencia BETWEEN 1 AND 31)
);

CREATE INDEX idx_recurrente_proximo ON recurrente (activo, proximo_cobro);

CREATE TABLE compra_msi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL,
    monto_total DECIMAL(19, 2) NOT NULL,
    numero_mensualidades INT NOT NULL,
    mensualidades_pagadas INT NOT NULL DEFAULT 0,
    cuenta_id BIGINT NOT NULL,
    categoria_id BIGINT,
    fecha_primer_cargo DATE NOT NULL,
    CONSTRAINT fk_msi_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT fk_msi_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT ck_msi_monto_positivo CHECK (monto_total > 0),
    CONSTRAINT ck_msi_num_mensualidades CHECK (numero_mensualidades >= 2),
    CONSTRAINT ck_msi_pagadas_rango CHECK (mensualidades_pagadas >= 0 AND mensualidades_pagadas <= numero_mensualidades)
);

CREATE INDEX idx_msi_cuenta ON compra_msi (cuenta_id);
