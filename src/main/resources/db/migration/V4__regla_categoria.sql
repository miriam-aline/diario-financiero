CREATE TABLE regla_categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto_contiene VARCHAR(120) NOT NULL,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT uk_regla_categoria_texto UNIQUE (texto_contiene),
    CONSTRAINT fk_regla_categoria_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
);

CREATE INDEX idx_regla_categoria_texto ON regla_categoria (texto_contiene);
CREATE UNIQUE INDEX uk_movimiento_hash_importacion ON movimiento (hash_importacion);
