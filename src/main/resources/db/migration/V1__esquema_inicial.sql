CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    presupuesto_mensual DECIMAL(19, 2),
    CONSTRAINT uk_categoria_nombre UNIQUE (nombre),
    CONSTRAINT ck_categoria_presupuesto_positivo CHECK (presupuesto_mensual IS NULL OR presupuesto_mensual > 0)
);

CREATE TABLE cuenta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    dia_corte INT,
    dia_pago INT,
    CONSTRAINT uk_cuenta_nombre UNIQUE (nombre),
    CONSTRAINT ck_cuenta_tipo CHECK (tipo IN ('EFECTIVO', 'DEBITO', 'CREDITO')),
    CONSTRAINT ck_cuenta_dia_corte CHECK (dia_corte IS NULL OR (dia_corte BETWEEN 1 AND 31)),
    CONSTRAINT ck_cuenta_dia_pago CHECK (dia_pago IS NULL OR (dia_pago BETWEEN 1 AND 31))
);

CREATE TABLE movimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    monto DECIMAL(19, 2) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    categoria_id BIGINT NOT NULL,
    cuenta_id BIGINT NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    origen VARCHAR(20) NOT NULL,
    hash_importacion VARCHAR(64),
    CONSTRAINT fk_movimiento_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT ck_movimiento_monto_positivo CHECK (monto > 0),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('INGRESO', 'GASTO')),
    CONSTRAINT ck_movimiento_origen CHECK (origen IN ('MANUAL', 'IMPORTADO'))
);

CREATE INDEX idx_movimiento_fecha ON movimiento (fecha);
CREATE INDEX idx_movimiento_categoria ON movimiento (categoria_id);
CREATE INDEX idx_movimiento_cuenta ON movimiento (cuenta_id);
CREATE INDEX idx_movimiento_hash ON movimiento (hash_importacion);
